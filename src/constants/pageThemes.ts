export function getPageTheme(key: string, overrides?: { title?: string; subtitle?: string; badge?: string }): PageTheme {
  const base = PAGE_THEMES[key] || PAGE_THEMES.home;
  if (!overrides) return base;
  return {
    ...base,
    title: overrides.title || base.title,
    subtitle: overrides.subtitle || base.subtitle,
    badge: overrides.badge || base.badge,
  };
}
